// ヘルパー関数：ダミー選択肢を生成
export function generateDummyChars(correctChars, count, allKanjiChars) {
  const dummies = [];
  const used = new Set(correctChars);

  while (dummies.length < count && allKanjiChars.length > 0) {
    const randomChar = allKanjiChars[Math.floor(Math.random() * allKanjiChars.length)];
    if (!used.has(randomChar)) {
      dummies.push(randomChar);
      used.add(randomChar);
    }
  }

  return dummies;
}

// ヘルパー関数：配列をシャッフル
export function shuffle(array) {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}
